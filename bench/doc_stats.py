"""Record counts quoted in docs, computed from the result JSON (never typed by hand).

    python -m bench.doc_stats                      # print the block for results/tpu
    python -m bench.doc_stats --write docs/RESULTS.md   # regenerate the marked block in place
    python -m bench.doc_stats --check docs/RESULTS.md   # exit 1 when the block has drifted

The block sits between BEGIN/END marker comments in the doc. tests/test_doc_stats.py runs the
same check, so a results change without a regenerated doc fails CI.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

from trbench.validate import is_dirty

BEGIN = "<!-- doc_stats:begin (generated by `python -m bench.doc_stats --write docs/RESULTS.md`; do not edit) -->"
END = "<!-- doc_stats:end -->"
DEFAULT_ROOT = "results/tpu"


def collect(root) -> dict:
    """Count records under root: {group: {"records", "dirty"}} plus totals.

    group = first path component under root (a record directly in root groups as ".").
    A record is a JSON object with "metrics" and "git"; other JSON counts as "other".
    """
    root = Path(root)
    groups: dict[str, Counter] = {}
    other = 0
    for path in sorted(root.rglob("*.json")):
        try:
            rec = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            other += 1
            continue
        if not (isinstance(rec, dict) and "metrics" in rec and "git" in rec):
            other += 1
            continue
        rel = path.relative_to(root)
        g = groups.setdefault(rel.parts[0] if len(rel.parts) > 1 else ".", Counter())
        g["records"] += 1
        g["dirty"] += is_dirty(rec)
    total = sum(g["records"] for g in groups.values())
    dirty = sum(g["dirty"] for g in groups.values())
    return {
        "groups": {k: dict(v) for k, v in groups.items()},
        "records": total,
        "dirty": dirty,
        "other_json": other,
    }


def render(stats, root=DEFAULT_ROOT) -> str:
    clean = stats["records"] - stats["dirty"]
    sentence = (
        f"`git.dirty` is true on {stats['dirty']} of the {stats['records']} records "
        f"under `{root}/` ({clean} clean). Per directory:"
    )
    lines = [
        BEGIN,
        "",
        sentence,
        "",
        "| directory | records | dirty | clean |",
        "|---|---|---|---|",
    ]
    for name, g in sorted(stats["groups"].items()):
        lines.append(f"| `{name}` | {g['records']} | {g['dirty']} | {g['records'] - g['dirty']} |")
    lines += ["", END]
    return "\n".join(lines)


def splice(text, block) -> str:
    """Replace the marked block in text; raises ValueError when the markers are missing."""
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise ValueError("doc_stats markers not found")
    return text[:i] + block + text[j + len(END) :]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--results", default=DEFAULT_ROOT)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", metavar="DOC", help="rewrite the marked block in DOC")
    g.add_argument("--check", metavar="DOC", help="fail when DOC's block differs")
    a = ap.parse_args(argv)
    block = render(collect(a.results), a.results)
    if not (a.write or a.check):
        print(block)
        return 0
    doc = Path(a.write or a.check)
    new = splice(doc.read_text(), block)
    if a.write:
        doc.write_text(new)
        return 0
    if new != doc.read_text():
        print(
            f"{doc}: doc_stats block is stale; run python -m bench.doc_stats --write {doc}",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
